-- «Не занесено» по фактам хаба (выпуск 2): пустой день вкладки в доказанную неделю фактов (fact_weeks ok) у человека,
-- сопоставленного с пользователем хаба, — его доли продаж за день из fact_accruals, а не все деньги страницы в окне
-- его графика; день без его смены или захода — выходной, не «не занесено». Иначе — по окну графика, как раньше.
-- Схема не меняется: как посчитан день, пишет reason.

UPDATE schema_docs
   SET description = '«Не занесено»: дни вкладок без значения за последние 45 дней, по которым хаб показывает деньги человека. В доказанную неделю фактов хаба (fact_weeks ok) у человека, сопоставленного с пользователем хаба, — его доли продаж за день (fact_accruals), день без его работы — выходной, не строка; иначе — деньги страниц недели в окне смены по карточке. Только сведения: в долг не идут'
 WHERE tbl = 'payroll_unentered' AND col = '';
UPDATE schema_docs
   SET description = 'Как посчитано или почему неизвестно: «по фактам хаба» — его доли продаж за день; «по окну графика» — все деньги страницы в окне смены из карточки; у unknown — почему'
 WHERE tbl = 'payroll_unentered' AND col = 'reason';
UPDATE schema_docs
   SET description = 'Начало окна: смены по карточке или, по фактам хаба, первой его работы дня на страницах модели, МСК'
 WHERE tbl = 'payroll_unentered' AND col = 'window_from';
UPDATE schema_docs
   SET description = 'Конец окна: смены по карточке или, по фактам хаба, последней его работы дня, МСК'
 WHERE tbl = 'payroll_unentered' AND col = 'window_to';
UPDATE schema_docs
   SET description = 'Net хаба за день человека, тысячные доллара: его доли продаж по фактам или всё в окне смены; при unknown — NULL'
 WHERE tbl = 'payroll_unentered' AND col = 'net_mills';
